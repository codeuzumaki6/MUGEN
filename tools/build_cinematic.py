# Original, non-verbal sound design. Authentic voice samples remain untouched.
random.seed(48)
rate=22050
sound_dir=ROOT/'Eida/assets/sound'
for name,duration in [('memory_build',7.1),('memory_transition',.30),('memory_release',.95)]:
    samples=[]
    smooth=0.0
    for i in range(round(rate*duration)):
        t=i/rate;p=t/duration
        smooth=.91*smooth+.09*random.uniform(-1,1)
        if name=='memory_build':
            envelope=min(1,t*3)*min(1,(duration-t)*4)
            value=(.14*math.sin(2*math.pi*(62*t+5*t*t))+.09*math.sin(2*math.pi*(125*t+16*t*t))+.18*smooth)*envelope
        elif name=='memory_transition':
            value=(.55*smooth+.10*math.sin(2*math.pi*(700*t-600*t*t)))*math.sin(math.pi*p)**2
        else:
            value=(.40*math.sin(2*math.pi*(95*t-30*t*t))+.45*smooth)*math.exp(-5*p)*min(1,t*100)
        samples.append(struct.pack('<h',round(max(-.95,min(.95,value))*32767)))
    with wave.open(str(sound_dir/(name+'.wav')),'wb') as w:
        w.setparams((1,2,rate,0,'NONE','not compressed'));w.writeframes(b''.join(samples))
